-- ============================================================
-- 059_push_subscriptions.sql — Web Push subscriptions (PWA)
--
-- One row per browser / installed PWA that opted into push
-- notifications. The row is written exclusively by the server
-- (POST /api/push/subscribe) with the service-role client, after
-- the caller's Supabase session is verified. The webhook handlers
-- read it with the service role to fan out a notification when a
-- new inbound message arrives.
--
-- `endpoint` is globally unique: the same browser subscription
-- must not be duplicated if the user enables notifications twice
-- (the API upserts on it and refreshes user_id / account_id).
--
-- Server-only: RLS is enabled with no client policies and direct
-- privileges are revoked below (same pattern as 050 / 058).
--
-- Idempotent — safe to run multiple times.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.push_subscriptions (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  -- Recipient. Notifications are only ever delivered to the user
  -- who created the subscription.
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  -- Tenancy scope. Lets the webhook resolve "every device in this
  -- account that wants inbox alerts" without joining profiles.
  account_id UUID NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
  -- Push service endpoint (FCM / APNs / Mozilla …). Opaque HTTPS
  -- URL — never parsed, only handed back to web-push.
  endpoint TEXT NOT NULL,
  -- Client public key (P-256, base64url) and auth secret used to
  -- encrypt the payload. Generated by the browser.
  p256dh TEXT NOT NULL,
  auth TEXT NOT NULL,
  user_agent TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_used_at TIMESTAMPTZ,
  CONSTRAINT push_subscriptions_endpoint_key UNIQUE (endpoint)
);

CREATE INDEX IF NOT EXISTS idx_push_subscriptions_account
  ON public.push_subscriptions(account_id, user_id);

CREATE INDEX IF NOT EXISTS idx_push_subscriptions_user
  ON public.push_subscriptions(user_id);

DROP TRIGGER IF EXISTS set_updated_at ON public.push_subscriptions;
CREATE TRIGGER set_updated_at BEFORE UPDATE ON public.push_subscriptions
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;

-- No client policies: subscriptions are managed by the API route
-- (service role) only. This keeps endpoint/key material out of the
-- browser's reach and prevents one member from deleting another
-- member's subscriptions.
REVOKE ALL ON TABLE public.push_subscriptions FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE
  ON TABLE public.push_subscriptions TO service_role;
